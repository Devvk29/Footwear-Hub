// Helper to generate default stock distribution per size
export const createDefaultStockForSizes = (sizes = [6, 7, 8, 9, 10], baseQty = 12) => {
  const stockObj = {};
  sizes.forEach((sz, idx) => {
    const variance = (idx % 3 === 0) ? -4 : (idx % 2 === 0) ? 3 : 0;
    stockObj[sz] = Math.max(2, baseQty + variance);
  });
  return stockObj;
};

export const getProductStockForSize = (product, size) => {
  if (!product || product.inStock === false) return 0;
  if (product.stockPerSize && product.stockPerSize[size] !== undefined) {
    return Number(product.stockPerSize[size]);
  }
  return 8;
};

export const getTotalProductStock = (product) => {
  if (!product || product.inStock === false) return 0;
  if (product.stockPerSize && typeof product.stockPerSize === 'object') {
    const total = Object.values(product.stockPerSize).reduce((acc, qty) => acc + (Number(qty) || 0), 0);
    return total;
  }
  const sizes = product.sizes || [7, 8, 9, 10];
  return sizes.length * 8;
};
